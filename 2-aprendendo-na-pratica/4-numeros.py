#tipos numeroricos que o python nos oferecem.


#inteiros (int)
numero_inteiro = 3 # quando colocamos um numero sozinho (sem ponto) ele ja é considerado um numero cheio
print("inteiro = ", numero_inteiro) 
#aqui, a funçao print vai imprimir a string "inteiro =" e a variavel numero_inteiro, depois da virgula


#real com ponto flutuante (float)
numero_real = 3.1415 # a diferença, é que o interpretador define um numero real atraves do ponto depois do numero
print("numero real =", numero_real)
#aqui, a funçao print vai imprimir a string "numero real =" e a variavel numero_real, depois da virgula


#type() é uma função que nos retorna o tipo de dado da variavel
print("tipo da variavel 'numero_inteiro' = ", type(numero_inteiro)) #essa função vai nos retornar o tipo da variavel numero_inteiro, que é um inteiro
print("tipo da variavel 'numero_real' = ", type(numero_real)) #essa função vai nos retornar o tipo da variavel numero_real, que é um float