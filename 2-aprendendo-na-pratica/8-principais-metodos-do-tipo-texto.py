nome = "Felipe Levi"

print(nome.upper()) # Converte todos os caracteres para maiúsculo
print(nome.lower()) # Converte todos os caracteres para minúsculo
print(nome.capitalize()) # Converte o primeiro caractere para maiúsculo e o restante para minúsculo
print(nome.title()) # Converte o primeiro caractere de cada palavra para maiúsculo e o restante para minúsculo